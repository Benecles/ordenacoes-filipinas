"""Integrate the generated Aula 11 figures into the lesson page.

Run directly: python3 tools/figkit/processo_a11_inject.py PATH_TO_AULA_11_HTML
The marker is replaced idempotently so every SVG stays generated by figkit.
"""

from pathlib import Path
import re
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
from processo_a11 import EXAM_THREAD, SOURCE, hero_panel, scope_panel, refiling_panel


MARKERS = ("<!-- A11 FIGURE 1 -->", "<!-- A11 FIGURE 2 -->", "<!-- A11 FIGURE 3 -->")


def hero_figure():
    hero = hero_panel()
    return f'''<figure class="a11-hero-figure" data-exam-thread="{EXAM_THREAD}">
{hero}
<figcaption>Jesse ocupa a posição de autor; Dalvo e Serotonina respondem pela cobrança solidária em posições próprias.</figcaption></figure>'''


def scope_figure():
    scope = tuple(scope_panel(n) for n in (1, 2, 3))
    step_cards = (
        '<section class="step on" data-panel="pci-a11-scope-1"><div class="card">'
        '<h3>O registro de Q4</h3><p>Jesse cobra de dois réus; a hipótese de ilegitimidade ainda não aconteceu.</p></div></section>'
        '<section class="step" data-panel="pci-a11-scope-2"><div class="card">'
        '<h3>Dalvo sai, Serotonina fica</h3><p>Se a hipótese de Q4 ocorrer, a decisão alcança uma parte e a causa prossegue contra a outra.</p></div></section>'
        '<section class="step" data-panel="pci-a11-scope-3"><div class="card">'
        '<h3>O único réu sai</h3><p>Uma variação de um fato retira Serotonina do polo passivo; a mesma decisão passa a encerrar toda a fase cognitiva.</p></div></section>'
    )
    return f'''<div class="scrolly a11-scope-scrolly" aria-label="Alcance da decisão na questão 4 de 2015">
  <div class="stage"><figure>{scope[0]}{scope[1]}{scope[2]}<figcaption><span>Fig. 2 · O réu que permanece mantém a fase aberta</span><span class="stage-count">1 / 3</span></figcaption></figure></div>
  <div class="steps">{step_cards}</div>
</div>'''


def refiling_figure():
    refiling = refiling_panel()
    return f'''<figure class="a11-refiling-figure" data-exam-thread="{EXAM_THREAD}">
{refiling}
<figcaption>A mesma pretensão segue sem julgamento; a nova ação depende do estado do vício, das despesas e do número de abandonos.</figcaption></figure>
<span class="src" hidden data-src="{SOURCE}; Barbosa Moreira, Temas de direito processual, quarta série, pp. 105–106; Didier Jr., Curso de direito processual civil, vol. 1, cap. 22, pp. 797, 800, 809; Lucon, comentário ao art. 354, p. 586." data-exam-thread="{EXAM_THREAD}"></span>'''


def inject(path):
    path = Path(path)
    source = path.read_text(encoding="utf-8")
    if all(source.count(marker) == 1 for marker in MARKERS):
        generated = (hero_figure(), scope_figure(), refiling_figure())
        for marker, figure in zip(MARKERS, generated):
            source = source.replace(marker, figure)
    else:
        generated_svgs = (hero_panel(),) + tuple(scope_panel(n) for n in (1, 2, 3)) + (refiling_panel(),)
        ids = ("pci-a11-hero", "pci-a11-scope-1", "pci-a11-scope-2", "pci-a11-scope-3", "pci-a11-refiling")
        for ident, svg in zip(ids, generated_svgs):
            pattern = rf'<svg\b(?=[^>]*\bid="{ident}")[^>]*>.*?</svg>'
            source, n = re.subn(pattern, svg, source, count=1, flags=re.S)
            if n != 1:
                raise ValueError(f"expected one generated SVG {ident!r} in {path}")
    path.write_text(source, encoding="utf-8")
    return 3


if __name__ == "__main__":
    if len(sys.argv) != 2:
        raise SystemExit("usage: processo_a11_inject.py PATH_TO_AULA_11_HTML")
    print(f"{sys.argv[1]}: {inject(sys.argv[1])} figures")
